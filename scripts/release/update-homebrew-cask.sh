#!/usr/bin/env bash
# Write the Homebrew cask for a published release into a checkout of
# shopware/homebrew-tap:
#
#   scripts/release/update-homebrew-cask.sh <version> <checksums.txt> <tap-dir>
#
# The cask installs the zip archives packaged by package-release.sh (glibc
# builds on Linux). It only writes Casks/shopware-lsp.rb; committing and
# pushing is the caller's job.
set -euo pipefail

version="${1:?usage: update-homebrew-cask.sh <version> <checksums.txt> <tap-dir>}"
checksums="${2:?usage: update-homebrew-cask.sh <version> <checksums.txt> <tap-dir>}"
tap="${3:?usage: update-homebrew-cask.sh <version> <checksums.txt> <tap-dir>}"

checksum() {
  local archive="shopware-lsp_${version}_$1.zip"
  local sum
  sum="$(awk -v name="$archive" '$2 == name { print $1 }' "$checksums")"
  if [ -z "$sum" ]; then
    echo "update-homebrew-cask: no checksum for $archive in $checksums" >&2
    exit 1
  fi
  echo "$sum"
}

darwin_arm64="$(checksum darwin_arm64)"
darwin_amd64="$(checksum darwin_amd64)"
linux_arm64="$(checksum linux_arm64)"
linux_amd64="$(checksum linux_amd64)"
base="https://github.com/shopware/shopware-lsp/releases/download/#{version}"

mkdir -p "$tap/Casks"
cat >"$tap/Casks/shopware-lsp.rb" <<EOF
# Generated by shopware/shopware-lsp scripts/release/update-homebrew-cask.sh.
cask "shopware-lsp" do
  version "$version"

  on_macos do
    on_arm do
      sha256 "$darwin_arm64"
      url "$base/shopware-lsp_#{version}_darwin_arm64.zip"
    end
    on_intel do
      sha256 "$darwin_amd64"
      url "$base/shopware-lsp_#{version}_darwin_amd64.zip"
    end
  end
  on_linux do
    on_arm do
      sha256 "$linux_arm64"
      url "$base/shopware-lsp_#{version}_linux_arm64.zip"
    end
    on_intel do
      sha256 "$linux_amd64"
      url "$base/shopware-lsp_#{version}_linux_amd64.zip"
    end
  end

  name "shopware-lsp"
  desc "Shopware Language Server"
  homepage "https://github.com/shopware/shopware-lsp"

  livecheck do
    skip "Auto-generated on release."
  end

  binary "shopware-lsp"

  # No zap stanza required
end
EOF
echo "wrote $tap/Casks/shopware-lsp.rb"
