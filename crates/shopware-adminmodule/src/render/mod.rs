//! A resolved module written as the files of an Administration module.
//!
//! Everything a plugin may hook into is part of the format version: the
//! component names, the block names and the methods `getListCriteria`,
//! `getColumns`, `getDetailCriteria`, `loadEntity`, `onSave` and `onCancel`.

mod script;
mod snippets;
mod template;

use crate::config::CONFIG_RELATIVE_PATH;
use crate::resolve::Module;
use script::{acl_js, detail_js, index_js, list_js};
use snippets::snippets;
use template::{detail_twig, list_twig};

/// The component set of the Administration the plugin targets.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Style {
    /// Shopware 6.7 and later: the Meteor components (`mt-*`).
    Meteor,
    /// Shopware 6.6: the classic components (`sw-*`).
    Classic,
}

/// A file of a module, relative to the directory of the module.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedFile {
    pub path: String,
    pub content: String,
    /// The file belongs to the plugin: it is written when it is missing
    /// and left alone afterwards.
    pub once: bool,
}

/// The directory the generator owns, relative to the module directory.
pub const GENERATED_DIRECTORY: &str = "generated";

fn js(value: &str) -> String {
    format!("'{}'", value.replace('\\', "\\\\").replace('\'', "\\'"))
}

fn attribute(value: &str) -> String {
    value.replace('&', "&amp;").replace('"', "&quot;")
}

/// `createdAt` as `created_at`, `acme-review` as `acme_review`.
fn snake(name: &str) -> String {
    let mut result = String::new();
    for character in name.chars() {
        if character == '-' {
            result.push('_');
        } else if character.is_uppercase() {
            if !result.is_empty() && !result.ends_with('_') {
                result.push('_');
            }
            result.extend(character.to_lowercase());
        } else {
            result.push(character);
        }
    }
    result
}

/// `productId` as `product-id`.
fn kebab(name: &str) -> String {
    snake(name).replace('_', "-")
}

fn capitalized(name: &str) -> String {
    let mut characters = name.chars();
    match characters.next() {
        Some(first) => first.to_uppercase().chain(characters).collect(),
        None => String::new(),
    }
}

fn header(lines: &mut Vec<String>) {
    lines.extend(
        [
            "/*",
            &format!(" * Generated by shopware-lsp from {CONFIG_RELATIVE_PATH}."),
            " * Do not edit: change the description and regenerate, or adjust this",
            " * from a file of your own with Shopware.Component.override.",
            " */",
        ]
        .map(str::to_owned),
    );
}

struct Names<'a> {
    module: &'a Module,
    style: Style,
}

impl Names<'_> {
    fn list(&self) -> String {
        format!("{}-list", self.module.name)
    }

    fn detail(&self) -> String {
        format!("{}-detail", self.module.name)
    }

    fn route(&self, name: &str) -> String {
        format!("{}.{name}", self.module.name.replace('-', "."))
    }

    fn snippet(&self, key: &str) -> String {
        format!("{}.{key}", self.module.name)
    }

    fn privilege(&self, role: &str) -> String {
        format!("{}.{role}", self.module.entity)
    }

    /// The condition a role allows something under: always without roles.
    fn can(&self, role: &str) -> String {
        match self.module.acl {
            Some(_) => format!("acl.can('{}')", self.privilege(role)),
            None => "true".to_owned(),
        }
    }

    fn model(&self) -> &'static str {
        match self.style {
            Style::Meteor => "v-model",
            Style::Classic => "v-model:value",
        }
    }

    fn page_directory(&self, managed: bool) -> &'static str {
        if managed { "generated/page" } else { "page" }
    }
}

/// The computed property that holds the options of a select.
fn options_name(field: &str) -> String {
    format!("{field}Options")
}

/// The files of `module`, sorted by path.
pub fn render(module: &Module, style: Style) -> Vec<GeneratedFile> {
    let names = Names { module, style };
    let mut files = vec![GeneratedFile {
        path: format!("{GENERATED_DIRECTORY}/index.js"),
        content: index_js(&names),
        once: false,
    }];
    if let Some(content) = acl_js(&names) {
        files.push(GeneratedFile {
            path: format!("{GENERATED_DIRECTORY}/acl.js"),
            content,
            once: false,
        });
    }
    let pages = [
        (
            names.list(),
            module.listing.managed,
            list_js(&names),
            list_twig(&names),
        ),
        (
            names.detail(),
            module.detail.managed,
            detail_js(&names),
            detail_twig(&names),
        ),
    ];
    for (component, managed, script, template) in pages {
        let directory = format!("{}/{component}", names.page_directory(managed));
        files.push(GeneratedFile {
            path: format!("{directory}/index.js"),
            content: script,
            once: !managed,
        });
        files.push(GeneratedFile {
            path: format!("{directory}/{component}.html.twig"),
            content: template,
            once: !managed,
        });
    }
    for locale in &module.locales {
        files.push(GeneratedFile {
            path: format!("{GENERATED_DIRECTORY}/snippet/{locale}.json"),
            content: snippets(&names, locale),
            once: false,
        });
    }
    files.sort_by(|left, right| left.path.cmp(&right.path));
    files
}
