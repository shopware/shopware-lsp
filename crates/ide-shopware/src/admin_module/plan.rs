//! What has to change on disk for the modules of a plugin to be what its
//! description says, and that as one workspace edit.

use swlsp_lsp::BoxError;
use swlsp_rewrite::{Builder, CreateFilePlan, DeleteFilePlan, DocumentPlan, WorkspacePlan};
use swlsp_syntax::{TextRange, TextSize};
use swlsp_uriutil::{file_uri, filepath};

use super::Generation;

/// The text that marks the index of a generated module.
const MARKER: &str = "Generated by shopware-lsp";

/// A file as the editor has it: its text and, when it is open, its version.
pub(crate) type Snapshot = (String, Option<i32>);

/// Reads a file by its path; `None` when it does not exist.
pub(crate) type Reader<'a> = &'a dyn Fn(&str) -> Result<Option<Snapshot>, BoxError>;

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum Action {
    Create(String),
    Update {
        old: String,
        version: Option<i32>,
        new: String,
    },
    Delete {
        old: String,
        version: Option<i32>,
    },
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct Change {
    /// The module the file belongs to; empty for a module the description
    /// no longer names.
    pub(crate) module: String,
    pub(crate) path: String,
    pub(crate) action: Action,
}

/// Reads from disk, for a check that does not see open documents.
pub(crate) fn read_disk(path: &str) -> Result<Option<Snapshot>, BoxError> {
    match std::fs::read(path) {
        Ok(content) => Ok(Some((String::from_utf8_lossy(&content).into_owned(), None))),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(error) => Err(format!("read {path}: {error}").into()),
    }
}

/// Every file below `directory`, sorted.
fn files_below(directory: &str, found: &mut Vec<String>) {
    let Ok(entries) = std::fs::read_dir(directory) else {
        return;
    };
    let mut paths: Vec<_> = entries.flatten().map(|entry| entry.path()).collect();
    paths.sort();
    for path in paths {
        let Some(text) = path.to_str() else {
            continue;
        };
        if path.is_dir() {
            if !path.is_symlink() {
                files_below(text, found);
            }
        } else {
            found.push(filepath::clean(text));
        }
    }
}

/// The modules below `admin` a description generated once and names no
/// more.
fn removed_modules(generation: &Generation) -> Vec<String> {
    let modules = filepath::join(&[generation.admin.as_str(), "module"]);
    let Ok(entries) = std::fs::read_dir(&modules) else {
        return Vec::new();
    };
    let mut removed: Vec<String> = entries
        .flatten()
        .filter_map(|entry| entry.file_name().into_string().ok())
        .filter(|name| !generation.described.contains(name))
        .filter(|name| {
            let index =
                filepath::join(&[generation.generated_directory(name).as_str(), "index.js"]);
            std::fs::read_to_string(index).is_ok_and(|source| source.contains(MARKER))
        })
        .collect();
    removed.sort();
    removed
}

fn import_line(module: &str) -> String {
    format!("import './module/{module}/generated';")
}

/// The entry file of the Administration: `main.ts` when the plugin has
/// one, else `main.js`.
fn entry_path(admin: &str) -> String {
    let typescript = filepath::join(&[admin, "main.ts"]);
    if std::path::Path::new(&typescript).is_file() {
        return typescript;
    }
    filepath::join(&[admin, "main.js"])
}

fn entry_change(
    generation: &Generation,
    removed: &[String],
    read: Reader,
) -> Result<Option<Change>, BoxError> {
    let path = entry_path(&generation.admin);
    let wanted: Vec<&String> = generation.modules.keys().collect();
    let Some((old, version)) = read(&path)? else {
        if wanted.is_empty() {
            return Ok(None);
        }
        let content: String = wanted
            .iter()
            .map(|module| import_line(module) + "\n")
            .collect();
        return Ok(Some(Change {
            module: wanted[0].clone(),
            path,
            action: Action::Create(content),
        }));
    };
    let imports = |module: &str| {
        let line = import_line(module);
        [line.clone(), line.replace('\'', "\"")]
    };
    let before = old.lines().count();
    let mut lines: Vec<&str> = old
        .lines()
        .filter(|line| {
            !removed
                .iter()
                .any(|module| imports(module).iter().any(|import| line.trim() == import))
        })
        .collect();
    let missing: Vec<String> = wanted
        .iter()
        .filter(|module| {
            !lines
                .iter()
                .any(|line| imports(module).iter().any(|import| line.trim() == import))
        })
        .map(|module| import_line(module))
        .collect();
    if missing.is_empty() && lines.len() == before {
        return Ok(None);
    }
    lines.extend(missing.iter().map(String::as_str));
    let mut new = lines.join("\n");
    if !new.is_empty() {
        new.push('\n');
    }
    let module = wanted
        .iter()
        .find(|module| missing.contains(&import_line(module)))
        .map(|module| (*module).clone())
        .unwrap_or_default();
    Ok(Some(Change {
        module,
        path,
        action: Action::Update { old, version, new },
    }))
}

/// Every change that makes the files what `generation` describes, in the
/// order of their paths.
pub(crate) fn changes(generation: &Generation, read: Reader) -> Result<Vec<Change>, BoxError> {
    let mut changes = Vec::new();
    for (module, targets) in &generation.modules {
        let directory = generation.module_directory(module);
        let generated = generation.generated_directory(module);
        for target in targets {
            let existing = read(&target.path)?;
            let action = match existing {
                None if target.once => {
                    // A page taken over starts as it was generated last.
                    let relative = target.path.strip_prefix(&directory).unwrap_or_default();
                    let before = read(&format!("{generated}{relative}"))?;
                    Action::Create(before.map_or_else(|| target.content.clone(), |(old, _)| old))
                }
                None => Action::Create(target.content.clone()),
                Some(_) if target.once => continue,
                Some((old, _)) if old == target.content => continue,
                Some((old, version)) => Action::Update {
                    old,
                    version,
                    new: target.content.clone(),
                },
            };
            changes.push(Change {
                module: module.clone(),
                path: target.path.clone(),
                action,
            });
        }
        let mut present = Vec::new();
        files_below(&generated, &mut present);
        for path in present {
            if targets.iter().any(|target| target.path == path) {
                continue;
            }
            if let Some((old, version)) = read(&path)? {
                changes.push(Change {
                    module: module.clone(),
                    path,
                    action: Action::Delete { old, version },
                });
            }
        }
    }
    let removed = removed_modules(generation);
    for module in &removed {
        let mut present = Vec::new();
        files_below(&generation.generated_directory(module), &mut present);
        for path in present {
            if let Some((old, version)) = read(&path)? {
                changes.push(Change {
                    module: String::new(),
                    path,
                    action: Action::Delete { old, version },
                });
            }
        }
    }
    changes.extend(entry_change(generation, &removed, read)?);
    changes.sort_by(|left, right| left.path.cmp(&right.path));
    Ok(changes)
}

/// The changes as one workspace edit.
pub(crate) fn workspace_plan(changes: Vec<Change>) -> Result<WorkspacePlan, BoxError> {
    let mut plan = WorkspacePlan::default();
    for change in changes {
        let uri = file_uri(&change.path);
        match change.action {
            Action::Create(content) => plan.creates.push(CreateFilePlan { uri, content }),
            Action::Update { old, version, new } => {
                let mut builder = Builder::new(&old);
                builder.replace_range(
                    TextRange::new(TextSize::from(0), TextSize::from(old.len() as u32)),
                    new,
                )?;
                plan.documents
                    .push(DocumentPlan::new(uri, version, old, builder.finish()?));
            }
            Action::Delete { old, version } => plan.deletes.push(DeleteFilePlan {
                uri,
                version,
                source: old,
            }),
        }
    }
    Ok(plan)
}
