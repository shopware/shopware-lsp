//! Generates `docs/inspections.md` from the production inspection registry
//! and fails when the committed reference is out of date. Regenerate with
//! `SHOPWARE_LSP_UPDATE_REFERENCE=1 cargo test -p swlsp-app inspection_reference`.

use std::fmt::Write;
use std::path::Path;

use serde_json::{Value, json};
use swlsp_lsp::Server;

use super::support::{TestClient, write_file};
use crate::workspace_factory_in;

fn render(catalog: &Value) -> String {
    let mut out = String::from(
        "# Inspection Reference\n\n\
         Every inspection the server registers, with the diagnostic codes it reports.\n\
         Configure them in `.config/shopware-lsp.yaml` (see the\n\
         [reference](reference.md)): `diagnostics.inspections.<id>` switches an\n\
         inspection, `diagnostics.rules.<code>` sets a code's severity. Suppress a code\n\
         on one line with an `@noinspection <code>` comment. Agents get the same\n\
         explanations from the MCP tool `shopware_explain_diagnostic`.\n\n\
         <!-- Generated by crates/app/src/tests/inspection_reference_test.rs from the\n\
         inspection registry; edit the inspection definitions, then regenerate with\n\
         SHOPWARE_LSP_UPDATE_REFERENCE=1 cargo test -p swlsp-app inspection_reference -->\n",
    );
    for inspection in catalog["inspections"].as_array().into_iter().flatten() {
        let languages: Vec<&str> = inspection["languages"]
            .as_array()
            .into_iter()
            .flatten()
            .filter_map(Value::as_str)
            .collect();
        let _ = write!(
            out,
            "\n## `{}`\n\n{}\n\nLanguages: {}",
            inspection["id"].as_str().unwrap_or_default(),
            inspection["description"].as_str().unwrap_or_default(),
            languages.join(", "),
        );
        if let Some(domain) = inspection["domain"].as_str() {
            let _ = write!(out, ". Domain: `{domain}`");
        }
        out.push_str(".\n\n| Code | Default severity | Enabled by default |\n|---|---|---|\n");
        for rule in inspection["rules"].as_array().into_iter().flatten() {
            let _ = writeln!(
                out,
                "| `{}` | {} | {} |",
                rule["id"].as_str().unwrap_or_default(),
                rule["defaultSeverity"].as_str().unwrap_or_default(),
                if rule["defaultEnabled"] == json!(true) {
                    "yes"
                } else {
                    "no"
                },
            );
        }
        // What to do about a code, where its rule says so.
        for rule in inspection["rules"].as_array().into_iter().flatten() {
            let help = &rule["help"];
            let Some(fix) = help["fix"].as_str() else {
                continue;
            };
            let _ = write!(
                out,
                "\n**`{}`**\n\n- Fix: {fix}\n",
                rule["id"].as_str().unwrap_or_default()
            );
            if let Some(exceptions) = help["exceptions"].as_str() {
                let _ = writeln!(out, "- Exceptions: {exceptions}");
            }
            if let Some(opt_out) = help["optOut"].as_str() {
                let _ = writeln!(out, "- Opt out: {opt_out}");
            }
        }
    }
    out
}

#[test]
fn inspection_reference_is_up_to_date() {
    let project = tempfile::tempdir().unwrap();
    let cache = tempfile::tempdir().unwrap();
    let root = project.path();
    write_file(
        root,
        "composer.json",
        r#"{"name":"acme/plugin","type":"shopware-platform-plugin","require":{"shopware/core":"6.6.0.0"}}"#,
    );
    let server = Server::new(None, "", "test");
    server.configure_project_detection(true, false);
    server.set_workspace_factory(workspace_factory_in(cache.path().to_path_buf()));
    let client = TestClient::start(&server);
    client.initialize(root, json!({}));
    client.wait_notification("shopware/indexingCompleted");
    let catalog = client.call("shopware/configuration/catalog", json!({}));
    client.shutdown().unwrap();
    // An explanation outlives its rule only by mistake, and every rule
    // says what to do about its findings (`RuleHelp`, registered with
    // `Registrar::rule_help` beside the inspection).
    assert_eq!(server.unknown_rule_help(), Vec::<&str>::new());
    let unexplained: Vec<&str> = catalog["inspections"]
        .as_array()
        .into_iter()
        .flatten()
        .flat_map(|inspection| inspection["rules"].as_array().into_iter().flatten())
        .filter(|rule| rule["help"]["fix"].as_str().is_none_or(str::is_empty))
        .filter_map(|rule| rule["id"].as_str())
        .collect();
    assert_eq!(
        unexplained,
        Vec::<&str>::new(),
        "diagnostic codes without help"
    );

    let expected = render(&catalog);
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../docs/inspections.md");
    if std::env::var_os("SHOPWARE_LSP_UPDATE_REFERENCE").is_some() {
        std::fs::write(&path, &expected).unwrap();
        return;
    }
    let actual = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        actual == expected,
        "docs/inspections.md is out of date; regenerate it with \
         SHOPWARE_LSP_UPDATE_REFERENCE=1 cargo test -p swlsp-app inspection_reference"
    );
}
