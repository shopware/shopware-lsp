//! Meteor component library declarations.

use std::sync::LazyLock;

use regex::Regex;

use crate::*;

pub(crate) const METEOR_PACKAGE_PATH: &str = "@shopware-ag/meteor-component-library";

static METEOR_EVENT_LISTENER_PATTERN: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r#"(?m)^[\t\n\f\r ]*(?:"(on[^"]+)"|(on[A-Za-z][A-Za-z0-9_:-]*))\?[\t\n\f\r ]*:"#)
        .expect("valid meteor event listener pattern")
});

static METEOR_LITERAL_TYPE_ALIAS_PATTERN: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(
        r"(?m)^[\t\n\f\r ]*(?:export[\t\n\f\r ]+)?type[\t\n\f\r ]+([A-Za-z_$][A-Za-z0-9_$]*)[\t\n\f\r ]*=[\t\n\f\r ]*([^;\n]+)[\t\n\f\r ]*;",
    )
    .expect("valid meteor literal alias pattern")
});

/// One `name: value` member of a TypeScript object type.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub(crate) struct TypeDeclarationField {
    pub name: String,
    pub value: String,
    pub optional: bool,
    /// Absolute byte offset of the (possibly quoted) name.
    pub offset: usize,
    /// Absolute byte offset of the value, if any.
    pub value_offset: Option<usize>,
    pub quoted: bool,
}

fn line_at(line_index: &LineIndex, offset: usize) -> u32 {
    line_index.position(offset as u32).0 + 1
}

/// Consumes the public declarations generated by vue-tsc for a Meteor
/// component.
pub(crate) fn parse_meteor_declaration(file_path: &str, source: &str) -> Option<VueComponent> {
    let base = filepath::base(file_path);
    if !base.starts_with("Mt") || !base.ends_with(".d.ts") {
        return None;
    }
    let name = camel_to_kebab(base.strip_suffix(".d.ts").unwrap_or(&base));
    if name.is_empty() {
        return None;
    }
    let line_index = LineIndex::new(source);
    let mut component = VueComponent {
        name,
        kind: ComponentRegistrationKind::Register,
        file_path: file_path.to_owned(),
        definition_path: file_path.to_owned(),
        line: 1,
        ..Default::default()
    };
    let literal_aliases = meteor_literal_type_aliases(source);

    if let Some(open) = declaration_object_start(source, "type __VLS_Props =") {
        for field in parse_type_declaration_fields(source, open) {
            let line = line_at(&line_index, field.offset);
            let event = meteor_event_name(&field.name);
            if !event.is_empty() {
                append_unique(&mut component.emits, &event);
                append_component_event(
                    &mut component.events,
                    VueComponentEvent {
                        name: event,
                        type_: field.value.trim().to_owned(),
                        documentation: admin_type_field_documentation(source, field.offset),
                        file_path: file_path.to_owned(),
                        line,
                        name_range: type_declaration_field_name_range(&field, &line_index, 0),
                    },
                );
                continue;
            }
            let mut prop = VueComponentProp {
                name: field.name.clone(),
                type_: field.value.trim().to_owned(),
                documentation: admin_type_field_documentation(source, field.offset),
                required: !field.optional,
                file_path: file_path.to_owned(),
                line,
                name_range: type_declaration_field_name_range(&field, &line_index, 0),
                ..Default::default()
            };
            (prop.allowed_values, prop.allowed_values_complete) =
                meteor_prop_allowed_values(&prop.type_, &literal_aliases);
            component.props.push(prop);
        }
    } else if let Some(open) = declaration_object_start(source, "ExtractPropTypes<") {
        for field in parse_type_declaration_fields(source, open) {
            let mut prop = VueComponentProp {
                name: field.name.clone(),
                file_path: file_path.to_owned(),
                line: line_at(&line_index, field.offset),
                documentation: admin_type_field_documentation(source, field.offset),
                name_range: type_declaration_field_name_range(&field, &line_index, 0),
                ..Default::default()
            };
            apply_runtime_prop_declaration(&mut prop, &field.value);
            (prop.allowed_values, prop.allowed_values_complete) =
                meteor_prop_allowed_values(&prop.type_, &literal_aliases);
            component.props.push(prop);
        }
    }

    if let Some(open) = meteor_slots_object_start(source) {
        for field in parse_type_declaration_fields(source, open) {
            let mut slot = VueComponentSlot {
                name: field.name.clone(),
                line: line_at(&line_index, field.offset),
                file_path: file_path.to_owned(),
                name_range: type_declaration_field_name_range(&field, &line_index, 0),
                payload_type: meteor_slot_payload_type(&field.value),
                members_complete: true,
                ..Default::default()
            };
            if let Some(open_payload) = slot.payload_type.find('{') {
                let mut payload_offset = field.offset;
                if let Some(relative) = source
                    .get(field.offset..)
                    .and_then(|rest| rest.find(slot.payload_type.as_str()))
                {
                    payload_offset += relative;
                }
                let payload_type = slot.payload_type.clone();
                for member in parse_type_declaration_fields(&payload_type, open_payload) {
                    append_slot_member(
                        &mut slot.members,
                        VueComponentSlotMember {
                            name: member.name.clone(),
                            type_: member.value.trim().to_owned(),
                            file_path: file_path.to_owned(),
                            line: line_at(&line_index, payload_offset + member.offset),
                            name_range: type_declaration_field_name_range(
                                &member,
                                &line_index,
                                payload_offset,
                            ),
                        },
                    );
                }
            }
            component.slots.push(slot);
        }
        // Package components have no Twig source; slot navigation points at
        // the declaration that owns the slot.
        component.template_path = file_path.to_owned();
    }
    for captures in METEOR_EVENT_LISTENER_PATTERN.captures_iter(source) {
        let Some(listener_match) = captures.get(1).or_else(|| captures.get(2)) else {
            continue;
        };
        let listener = listener_match.as_str();
        let event = meteor_event_name(listener);
        if event.is_empty() {
            continue;
        }
        append_unique(&mut component.emits, &event);
        let start = listener_match.start();
        let end = listener_match.end();
        append_component_event(
            &mut component.events,
            VueComponentEvent {
                name: event,
                documentation: admin_type_field_documentation(source, start),
                file_path: file_path.to_owned(),
                line: line_at(&line_index, start),
                name_range: source_range_at(
                    &line_index,
                    start as u32,
                    end as u32,
                    is_admin_type_identifier(listener),
                ),
                ..Default::default()
            },
        );
    }
    apply_meteor_runtime_prop_compatibility(&mut component);
    Some(component)
}

pub(crate) fn meteor_literal_type_aliases(source: &str) -> HashMap<String, Vec<String>> {
    let mut result = HashMap::new();
    for captures in METEOR_LITERAL_TYPE_ALIAS_PATTERN.captures_iter(source) {
        let (Some(name), Some(value)) = (captures.get(1), captures.get(2)) else {
            continue;
        };
        let (values, complete) = vue_string_literal_union_values(value.as_str());
        if complete && !values.is_empty() {
            result.insert(name.as_str().to_owned(), values);
        }
    }
    result
}

pub(crate) fn meteor_prop_allowed_values(
    value: &str,
    aliases: &HashMap<String, Vec<String>>,
) -> (Vec<String>, bool) {
    let value = vue_prop_value_type(value);
    if value.trim().is_empty() {
        return (Vec::new(), false);
    }
    let mut values = Vec::new();
    let mut complete = true;
    for branch in split_admin_type_top_level(&value, b'|') {
        let branch = trim_admin_type_parentheses(branch.trim());
        match branch {
            "null" | "undefined" | "void" | "never" => continue,
            _ => {}
        }
        if let Some(literal) = decode_admin_type_string_literal(branch) {
            append_allowed_value(&mut values, &literal);
            continue;
        }
        if let Some(alias_values) = aliases.get(branch)
            && !alias_values.is_empty()
        {
            for alias_value in alias_values {
                append_allowed_value(&mut values, alias_value);
            }
            continue;
        }
        complete = false;
    }
    let complete = complete && !values.is_empty();
    (values, complete)
}

/// Preserves public inputs which Meteor accepts at runtime although its
/// generated declaration is narrower (`mt-link.to`, `mt-icon.size`).
pub(crate) fn apply_meteor_runtime_prop_compatibility(component: &mut VueComponent) {
    let name = component.name.clone();
    for prop in &mut component.props {
        match format!("{}.{}", name, prop.name).as_str() {
            "mt-link.to" => prop.type_ = merge_vue_types(&[prop.type_.as_str(), "object"]),
            "mt-icon.size" => prop.type_ = merge_vue_types(&[prop.type_.as_str(), "number"]),
            _ => {}
        }
    }
}

pub(crate) fn meteor_slot_payload_type(value: &str) -> String {
    let value = value.trim();
    if value.is_empty() || value == "null" || value == "void" {
        return String::new();
    }
    if value.starts_with('(')
        && let Some(close) = matching_slot_delimiter(value, 0, b'(', b')')
    {
        let mut parameter = value[1..close].trim();
        if parameter.is_empty() {
            return String::new();
        }
        let first = split_slot_top_level(parameter, b',');
        if let Some(first) = first.first() {
            parameter = first.trim();
        }
        if let Some(colon) = index_slot_top_level(parameter, b':') {
            return parameter[colon + 1..].trim().to_owned();
        }
        return String::new();
    }
    if let Some(open) = value.find('{')
        && let Some(close) = balanced_brace_end(value, open)
    {
        return value[open..=close].trim().to_owned();
    }
    value.to_owned()
}

pub(crate) fn declaration_object_start(source: &str, marker: &str) -> Option<usize> {
    let marker_offset = source.find(marker)?;
    let relative = source[marker_offset + marker.len()..].find('{')?;
    Some(marker_offset + marker.len() + relative)
}

pub(crate) fn meteor_slots_object_start(source: &str) -> Option<usize> {
    ["slots: Readonly<", "slots:"]
        .iter()
        .find_map(|marker| declaration_object_start(source, marker))
}

pub(crate) fn parse_type_declaration_fields(
    source: &str,
    open: usize,
) -> Vec<TypeDeclarationField> {
    let Some(close) = balanced_brace_end(source, open) else {
        return Vec::new();
    };
    let body = &source[open + 1..close];
    let segments = split_top_level_declarations(body, open + 1);
    segments
        .iter()
        .filter_map(|segment| parse_type_declaration_field(&segment.text, segment.offset))
        .collect()
}

#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub(crate) struct DeclarationSegment {
    pub text: String,
    pub offset: usize,
}

pub(crate) fn split_top_level_declarations(
    body: &str,
    base_offset: usize,
) -> Vec<DeclarationSegment> {
    let bytes = body.as_bytes();
    let mut result = Vec::new();
    let mut start = 0;
    let mut state = DeclarationScanState::default();
    let mut index = 0;
    while index < bytes.len() {
        state.consume(bytes, &mut index);
        if state.in_literal_or_comment() {
            index += 1;
            continue;
        }
        match bytes[index] {
            b'{' => state.braces += 1,
            b'}' => state.braces -= 1,
            b'(' => state.parens += 1,
            b')' => state.parens -= 1,
            b'[' => state.brackets += 1,
            b']' => state.brackets -= 1,
            b'<' => state.angles += 1,
            b'>' => {
                if state.angles > 0 {
                    state.angles -= 1;
                }
            }
            b';' | b','
                if state.braces == 0
                    && state.parens == 0
                    && state.brackets == 0
                    && state.angles == 0 =>
            {
                result.push(DeclarationSegment {
                    text: lossy_slice(body, start, index),
                    offset: base_offset + start,
                });
                start = index + 1;
            }
            _ => {}
        }
        index += 1;
    }
    let rest = lossy_slice(body, start, body.len());
    if !rest.trim().is_empty() {
        result.push(DeclarationSegment {
            text: rest,
            offset: base_offset + start,
        });
    }
    result
}

/// Byte slice of `value` as a string; split points are always ASCII
/// delimiters, so this is exact for valid input.
fn lossy_slice(value: &str, start: usize, end: usize) -> String {
    String::from_utf8_lossy(&value.as_bytes()[start.min(end)..end]).into_owned()
}

#[derive(Clone, Copy, Debug, Default)]
pub(crate) struct DeclarationScanState {
    pub quote: u8,
    pub escaped: bool,
    pub line_comment: bool,
    pub block_comment: bool,
    pub braces: i32,
    pub parens: i32,
    pub brackets: i32,
    pub angles: i32,
}

impl DeclarationScanState {
    pub(crate) fn in_literal_or_comment(&self) -> bool {
        self.quote != 0 || self.line_comment || self.block_comment
    }

    pub(crate) fn consume(&mut self, source: &[u8], index: &mut usize) {
        let current = source[*index];
        if self.line_comment {
            if current == b'\n' {
                self.line_comment = false;
            }
            return;
        }
        if self.block_comment {
            if current == b'*' && *index + 1 < source.len() && source[*index + 1] == b'/' {
                self.block_comment = false;
                *index += 1;
            }
            return;
        }
        if self.quote != 0 {
            if self.escaped {
                self.escaped = false;
                return;
            }
            if current == b'\\' {
                self.escaped = true;
                return;
            }
            if current == self.quote {
                self.quote = 0;
            }
            return;
        }
        if current == b'/' && *index + 1 < source.len() {
            match source[*index + 1] {
                b'/' => {
                    self.line_comment = true;
                    *index += 1;
                    return;
                }
                b'*' => {
                    self.block_comment = true;
                    *index += 1;
                    return;
                }
                _ => {}
            }
        }
        if current == b'\'' || current == b'"' || current == b'`' {
            self.quote = current;
        }
    }
}

pub(crate) fn balanced_brace_end(source: &str, open: usize) -> Option<usize> {
    let bytes = source.as_bytes();
    if open >= bytes.len() || bytes[open] != b'{' {
        return None;
    }
    let mut depth = 0;
    let mut state = DeclarationScanState::default();
    let mut index = open;
    while index < bytes.len() {
        state.consume(bytes, &mut index);
        if !state.in_literal_or_comment() {
            match bytes[index] {
                b'{' => depth += 1,
                b'}' => {
                    depth -= 1;
                    if depth == 0 {
                        return Some(index);
                    }
                }
                _ => {}
            }
        }
        index += 1;
    }
    None
}

pub(crate) fn parse_type_declaration_field(
    text: &str,
    absolute_offset: usize,
) -> Option<TypeDeclarationField> {
    let (trimmed, skipped) = trim_declaration_prefix(text);
    if trimmed.is_empty() {
        return None;
    }
    let name_end = declaration_name_end(trimmed)?;
    if name_end == 0 {
        return None;
    }
    let mut raw_name = trimmed[..name_end].trim();
    let optional = raw_name.ends_with('?');
    raw_name = raw_name.strip_suffix('?').unwrap_or(raw_name).trim();
    raw_name = raw_name.strip_prefix("readonly ").unwrap_or(raw_name);
    let name = raw_name.trim_matches(|c| c == '\'' || c == '"');
    if name.is_empty() || name.contains([' ', '\t', '\r', '\n']) {
        return None;
    }
    let bytes = trimmed.as_bytes();
    let mut value_start = name_end;
    while value_start < bytes.len() && matches!(bytes[value_start], b'?' | b' ' | b'\t') {
        value_start += 1;
    }
    let mut value = String::new();
    let mut value_offset = None;
    if value_start < bytes.len() && bytes[value_start] == b':' {
        let mut offset = value_start + 1;
        while offset < bytes.len() && is_ascii_space(bytes[offset]) {
            offset += 1;
        }
        value = lossy_slice(trimmed, offset, bytes.len()).trim().to_owned();
        value_offset = Some(offset);
    } else if value_start < bytes.len() && bytes[value_start] == b'(' {
        value = trimmed[value_start..].trim().to_owned();
        value_offset = Some(value_start);
    }
    let name_offset = trimmed.find(raw_name).unwrap_or(0);
    let raw = raw_name.as_bytes();
    Some(TypeDeclarationField {
        name: name.to_owned(),
        value,
        optional,
        offset: absolute_offset + skipped + name_offset,
        value_offset: value_offset.map(|offset| absolute_offset + skipped + offset),
        quoted: raw.len() >= 2
            && (raw[0] == b'\'' || raw[0] == b'"')
            && raw[raw.len() - 1] == raw[0],
    })
}

pub(crate) fn type_declaration_field_name_range(
    field: &TypeDeclarationField,
    line_index: &LineIndex,
    base_offset: usize,
) -> AdminSourceRange {
    if field.name.is_empty() {
        return AdminSourceRange::default();
    }
    let mut start = base_offset + field.offset;
    if field.quoted {
        start += 1;
    }
    let end = start + field.name.len();
    source_range_at(line_index, start as u32, end as u32, !field.quoted)
}

/// Strips leading whitespace and comments; returns the rest and the number
/// of skipped bytes.
pub(crate) fn trim_declaration_prefix(text: &str) -> (&str, usize) {
    let mut offset = 0;
    loop {
        let rest = &text[offset..];
        let trimmed = rest.trim_start();
        offset += rest.len() - trimmed.len();
        if trimmed.starts_with("/*") {
            let Some(end) = trimmed.find("*/") else {
                return ("", text.len());
            };
            offset += end + 2;
            continue;
        }
        if trimmed.starts_with("//") {
            let Some(end) = trimmed.find('\n') else {
                return ("", text.len());
            };
            offset += end + 1;
            continue;
        }
        return (trimmed, offset);
    }
}

pub(crate) fn declaration_name_end(text: &str) -> Option<usize> {
    let mut quote = 0u8;
    let mut escaped = false;
    for (index, &current) in text.as_bytes().iter().enumerate() {
        if quote != 0 {
            if escaped {
                escaped = false;
                continue;
            }
            if current == b'\\' {
                escaped = true;
                continue;
            }
            if current == quote {
                quote = 0;
            }
            continue;
        }
        if current == b'\'' || current == b'"' {
            quote = current;
            continue;
        }
        if current == b':' || current == b'(' {
            return Some(index);
        }
    }
    None
}

pub(crate) fn apply_runtime_prop_declaration(prop: &mut VueComponentProp, value: &str) {
    let Some(open) = value.find('{') else {
        return;
    };
    for field in parse_type_declaration_fields(value, open) {
        match field.name.as_str() {
            "type" => prop.type_ = meteor_runtime_type(&field.value),
            "required" => prop.required = field.value.trim() == "true",
            _ => {}
        }
    }
}

pub(crate) fn meteor_runtime_type(value: &str) -> String {
    let value = value.trim();
    if let Some(start) = value.find("PropType<") {
        let inner = &value[start + "PropType<".len()..];
        if let Some(end) = inner.rfind('>') {
            return inner[..end].trim().to_owned();
        }
    }
    value
        .strip_suffix("Constructor")
        .unwrap_or(value)
        .to_owned()
}

pub(crate) fn meteor_event_name(listener: &str) -> String {
    if !listener.starts_with("on") || listener.len() <= 2 {
        return String::new();
    }
    let event = &listener[2..];
    let first = event.as_bytes()[0];
    if !first.is_ascii_uppercase() {
        return String::new();
    }
    let event = format!("{}{}", (first as char).to_ascii_lowercase(), &event[1..]);
    camel_to_kebab(&event)
}

pub(crate) fn append_unique(values: &mut Vec<String>, value: &str) {
    if value.is_empty() || values.iter().any(|existing| existing == value) {
        return;
    }
    values.push(value.to_owned());
}
